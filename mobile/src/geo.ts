export const DEFAULT_COUNTRY = "IN";

export function countryByCode(code?: string) {
  const needle = (code || DEFAULT_COUNTRY).toUpperCase();
  return COUNTRIES.find((country) => country.code === needle) ?? COUNTRIES.find((country) => country.code === DEFAULT_COUNTRY)!;
}

export function countryByName(name?: string) {
  const needle = (name || "").trim().toLowerCase();
  if (!needle) return countryByCode(DEFAULT_COUNTRY);
  return (
    COUNTRIES.find((country) => country.name.toLowerCase() === needle || country.code.toLowerCase() === needle) ??
    countryByCode(DEFAULT_COUNTRY)
  );
}

export function statesFor(countryCode?: string) {
  return STATES_BY_COUNTRY[(countryCode || DEFAULT_COUNTRY).toUpperCase()] ?? [];
}

export function isIndia(countryCode?: string) {
  return (countryCode || DEFAULT_COUNTRY).toUpperCase() === "IN";
}

export function isValidPostal(countryCode: string | undefined, postal: string) {
  const value = postal.trim();
  if (isIndia(countryCode)) return /^\d{6}$/.test(value);
  return /^[A-Za-z0-9][A-Za-z0-9\s-]{1,11}$/.test(value);
}

export function isValidPhone(phone: string) {
  const digits = phone.replace(/\D/g, "");
  return digits.length >= 8 && digits.length <= 15;
}

export function postalLooksComplete(postal: string, countryCode?: string) {
  const value = postal.trim();
  if (isIndia(countryCode)) return /^\d{6}$/.test(value);
  return value.length >= 4;
}

export function enabledCountries(config?: { allowInternational?: boolean; enabledCountryCodes?: string[] }) {
  if (config?.allowInternational === false) {
    return COUNTRIES.filter((country) => country.code === DEFAULT_COUNTRY);
  }
  const codes = (config?.enabledCountryCodes ?? []).map((code) => code.toUpperCase()).filter(Boolean);
  if (!codes.length) return COUNTRIES;
  const allowed = new Set(codes);
  return COUNTRIES.filter((country) => allowed.has(country.code));
}

export function withDial(phone: string, dial: string) {
  const trimmed = phone.trim();
  if (!trimmed) return trimmed;
  if (trimmed.startsWith("+")) return trimmed;
  const digits = trimmed.replace(/\D/g, "");
  const dialDigits = dial.replace(/\D/g, "");
  if (dialDigits && digits.startsWith(dialDigits)) return `+${digits}`;
  return `${dial} ${trimmed}`.trim();
}

export function formatAddressLine(address: {
  line1?: string;
  landmark?: string;
  city?: string;
  state?: string;
  pincode?: string;
  country?: string;
}) {
  return [
    address.line1,
    address.landmark,
    [address.city, address.state, address.pincode].filter(Boolean).join(" "),
    address.country,
  ]
    .filter(Boolean)
    .join(", ");
}
